// Generates src/lib/api/schema.gen.ts from openapi.json (the committed backend contract).
//
//   npm run gen:api          write the file
//   npm run gen:api:check    regenerate to a temp file; exit 1 if the committed file differs
import { mkdtempSync, readFileSync, writeFileSync, existsSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const specPath = join(root, "openapi.json");
const target = join(root, "src", "lib", "api", "schema.gen.ts");

const HEADER = `/**
 * GENERATED FILE, DO NOT EDIT.
 * Generated by scripts/gen-api.mjs from web/openapi.json (npm run gen:api).
 * Change the backend, run \`uv run python scripts/export_openapi.py\`, then regenerate.
 */

`;

const normalise = (text) => text.replace(/\r\n/g, "\n");

async function render() {
  const ast = await openapiTS(pathToFileURL(specPath));
  return HEADER + astToString(ast);
}

const check = process.argv.includes("--check");
const fresh = await render();

if (!check) {
  writeFileSync(target, fresh, { encoding: "utf8" });
  console.log(`wrote ${target}`);
} else {
  const dir = mkdtempSync(join(tmpdir(), "gen-api-"));
  const tmpFile = join(dir, "schema.gen.ts");
  writeFileSync(tmpFile, fresh, "utf8");
  try {
    const committed = existsSync(target) ? normalise(readFileSync(target, "utf8")) : null;
    if (committed === null || committed !== normalise(readFileSync(tmpFile, "utf8"))) {
      console.error(
        "\nThe generated API client is stale: src/lib/api/schema.gen.ts does not match " +
          "web/openapi.json.\nRun `npm run gen:api` in web/ and commit the result.\n",
      );
      process.exitCode = 1;
    } else {
      console.log("generated API client is up to date");
    }
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}
